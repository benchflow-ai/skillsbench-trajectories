#!/usr/bin/env python3
"""
Coverage-guided fuzzing driver for ujson library using atheris.

This fuzz driver targets the key functions in ujson:
1. ujson.loads() / ujson.decode() - HIGHEST PRIORITY - JSON parsing
2. ujson.dumps() / ujson.encode() - JSON encoding

Run with: python fuzz.py
"""

import atheris
import sys


# Instrument imports for coverage-guided fuzzing
with atheris.instrument_imports():
    import ujson


def TestOneInput(data: bytes) -> None:
    """
    Fuzz target function that tests ujson parsing and encoding.

    Args:
        data: Random bytes generated by the fuzzer
    """
    # Test 1: Try ujson.loads() with bytes directly (ujson accepts bytes)
    try:
        result = ujson.loads(data)
        # If parsing succeeded, also test encoding the result back
        try:
            ujson.dumps(result)
        except (ValueError, TypeError, OverflowError, RecursionError):
            pass
    except (ValueError, TypeError, UnicodeDecodeError, OverflowError, RecursionError):
        pass

    # Test 2: Try decoding bytes to string first, then call ujson.loads()
    try:
        decoded_str = data.decode('utf-8')
        result = ujson.loads(decoded_str)
        # If parsing succeeded, also test encoding the result back
        try:
            ujson.dumps(result)
        except (ValueError, TypeError, OverflowError, RecursionError):
            pass
    except (ValueError, TypeError, UnicodeDecodeError, OverflowError, RecursionError):
        pass

    # Test 3: Try ujson.decode() (alias for loads) with bytes
    try:
        result = ujson.decode(data)
        try:
            ujson.encode(result)
        except (ValueError, TypeError, OverflowError, RecursionError):
            pass
    except (ValueError, TypeError, UnicodeDecodeError, OverflowError, RecursionError):
        pass


if __name__ == "__main__":
    atheris.Setup(sys.argv, TestOneInput)
    atheris.Fuzz()
